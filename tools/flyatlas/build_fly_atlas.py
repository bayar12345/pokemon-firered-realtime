"""Builds the Fly journey picture for the ROM: graphics/fly_atlas/* and src/data/fly_atlas.h.
Usage: python3 tools/flyatlas/build_fly_atlas.py   (re-run after adding or moving outdoor maps)"""
import sys,struct,json,collections
from pathlib import Path
sys.path.insert(0,str(Path(__file__).parent))
import numpy as np
from PIL import Image
from atlas3 import build
from place import world_layout,maps
P=Path(__file__).resolve().parents[2];OUT=P/'graphics/fly_atlas';OUT.mkdir(parents=True,exist_ok=True)
MT=4  # screen pixels per metatile in the flight view
comp=world_layout()
img8,(x0,y0,W,H)=build(comp)
img=img8.resize((W*MT,H*MT),Image.LANCZOS)
img=img.crop((0,0,img.width//8*8,img.height//8*8))
arr=np.asarray(img).astype(np.int32)
TW,TH=img.width//8,img.height//8
tiles=arr.reshape(TH,8,TW,8,3).transpose(0,2,1,3,4).reshape(TH*TW,64,3)
# cluster tiles into 16 palette groups by colour content (k-means on 4x4x4 colour histograms)
q=(tiles//64);hidx=q[...,0]*16+q[...,1]*4+q[...,2]
hist=np.zeros((len(tiles),64),np.float32)
np.add.at(hist,(np.repeat(np.arange(len(tiles)),64),hidx.ravel()),1)
hist/=64
rng=np.random.default_rng(3);NPAL=15  # palette 15 is the clouds
cent=hist[rng.choice(len(hist),NPAL,replace=False)]
for it in range(25):
    d=((hist[:,None,:]-cent[None,:,:])**2).sum(2);lab=d.argmin(1)
    for k in range(NPAL):
        m=lab==k
        cent[k]=hist[m].mean(0) if m.any() else hist[rng.integers(len(hist))]
palettes=[]
for k in range(NPAL):
    px=tiles[lab==k].reshape(-1,3)
    if len(px)==0:palettes.append(np.zeros((15,3),int));continue
    sample=px[rng.choice(len(px),min(len(px),60000),replace=False)].astype(np.uint8)
    pim=Image.fromarray(sample.reshape(1,-1,3));qq=pim.quantize(colors=15,method=Image.Quantize.MEDIANCUT,dither=Image.Dither.NONE)
    pl=np.array(qq.getpalette()[:45]).reshape(15,3);palettes.append(pl)
palettes=np.stack(palettes)
tilebytes=[];tpal=[];pool={};mapidx=[]
for t,k in zip(tiles,lab):
    pl=palettes[k];d=((t[:,None,:]-pl[None,:,:])**2).sum(2);v=d.argmin(1)+1
    b=bytes(int(v[i])|(int(v[i+1])<<4) for i in range(0,64,2))
    if b not in pool:pool[b]=len(pool);tilebytes.append(b)
    mapidx.append(pool[b]);tpal.append(int(k))
(OUT/'tiles.4bpp').write_bytes(b''.join(tilebytes))
(OUT/'map.bin').write_bytes(b''.join(struct.pack('<H',v) for v in mapidx))
(OUT/'pals.bin').write_bytes(bytes(a|(b<<4) for a,b in zip(tpal[0::2],tpal[1::2]+[0]*(len(tpal)%2))))
gpal=[]
for pl in palettes:
    gpal+=[0]+[(int(c[0])>>3)|((int(c[1])>>3)<<5)|((int(c[2])>>3)<<10) for c in pl]
(OUT/'palettes.gbapal').write_bytes(struct.pack('<%dH'%len(gpal),*gpal))
# preview rebuilt from the GBA data
prev=Image.new('RGB',(TW*8,TH*8));pp=prev.load();P16=[[((v&31)<<3,((v>>5)&31)<<3,((v>>10)&31)<<3) for v in gpal[i*16:i*16+16]] for i in range(NPAL)]
for n,(ti,pi) in enumerate(zip(mapidx,tpal)):
    b=tilebytes[ti];tx,ty=n%TW,n//TW
    for k in range(64):
        c=(b[k//2]>>4) if k&1 else b[k//2]&15;pp[tx*8+k%8,ty*8+k//8]=P16[pi][c]
prev.save('/tmp/fly_gba_preview.png')
# map positions (metatile origin of each map in flight-view pixels)
names=sorted(comp,key=lambda m:m)
consts={m:None for m in names}
rows=[]
for m in names:
    mx,my=comp[m];rows.append((m,(mx-x0)*MT,(my-y0)*MT))
h=['// Generated by tools/flyatlas/build_fly_atlas.py. Do not edit.',
 f'#define FLY_ATLAS_TW {TW}',f'#define FLY_ATLAS_TH {TH}',f'#define FLY_ATLAS_MT {MT}',
 'static const u32 sFlyAtlasTiles[] = INCBIN_U32("graphics/fly_atlas/tiles.4bpp");',
 'static const u16 sFlyAtlasMap[] = INCBIN_U16("graphics/fly_atlas/map.bin");',
 'static const u8 sFlyAtlasPals[] = INCBIN_U8("graphics/fly_atlas/pals.bin");',
 'static const u16 sFlyAtlasPalettes[] = INCBIN_U16("graphics/fly_atlas/palettes.gbapal");',
 'static const u32 sFlyCloudTiles[] = INCBIN_U32("graphics/fly_atlas/cloud_tiles.4bpp");',
 'static const u16 sFlyCloudMap[] = INCBIN_U16("graphics/fly_atlas/cloud_map.bin");',
 'static const u16 sFlyCloudPal[] = INCBIN_U16("graphics/fly_atlas/cloud_pal.gbapal");',
 'struct FlyAtlasMap { u16 mapGroupNum; s16 x, y; };',
 'static const struct FlyAtlasMap sFlyAtlasMaps[] = {']
for m,x,y in rows:h.append(f'    {{(MAP_GROUP({m})<<8)|MAP_NUM({m}), {x}, {y}}},')
h.append('};')
(P/'src/data/fly_atlas.h').write_text('\n'.join(h)+'\n')
print(json.dumps({'size':[TW*8,TH*8],'unique_tiles':len(tilebytes),'bytes':len(tilebytes)*32+len(mapidx)*2+len(tpal)//2+512,'maps':len(rows)}))
