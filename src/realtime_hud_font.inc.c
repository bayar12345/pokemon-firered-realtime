static void RtTinyPrint(u8 window, u16 x, u16 y, const u8 *text, u8 color)
{
    u16 index, col, row, px, py, offset;
    u8 c, bits, *data = (u8 *)GetWindowAttribute(sRt->winIds[window], WINDOW_TILE_DATA);
    u16 width = sRtWindowTemplates[window].width;
    while ((c = *text++) != EOS && x + 5 < width * 8)
    {
        if (c >= CHAR_A && c <= CHAR_Z) index = c - CHAR_A;
        else if (c >= CHAR_a && c <= CHAR_z) index = c - CHAR_a;
        else if (c >= CHAR_0 && c <= CHAR_9) index = 26 + c - CHAR_0;
        else if (c == CHAR_HYPHEN) index = 36;
        else if (c == CHAR_PERIOD) index = 37;
        else if (c == CHAR_SLASH) index = 38;
        else if (c == CHAR_COLON) index = 39;
        else if (c == CHAR_SPACE) index = 40;
        else index = 41;
        for (col = 0; col < 5; col++)
        {
            bits = sRtTinyFont[index][col];
            for (row = 0; row < 7; row++)
            {
                if (!(bits & (1 << row))) continue;
                px = x + col; py = y + row;
                offset = ((py / 8) * width + px / 8) * 32 + (py & 7) * 4 + (px & 7) / 2;
                if (px & 1) data[offset] = (data[offset] & 15) | (color << 4);
                else data[offset] = (data[offset] & 0xF0) | color;
            }
        }
        x += 6;
    }
}
